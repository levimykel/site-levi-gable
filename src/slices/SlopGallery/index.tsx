import type { Content } from "@prismicio/client";
import { PrismicNextImage } from "@prismicio/next";
import { PrismicRichText, type SliceComponentProps } from "@prismicio/react";
import { wobble } from "@/lib/wobble";

export type SlopGalleryProps = SliceComponentProps<Content.SlopGallerySlice>;

export default function SlopGallery({ slice }: SlopGalleryProps) {
  return (
    <section data-slice-type={slice.slice_type} data-slice-variation={slice.variation} className="slop-gallery">
      <div className="slice-heading">
        <PrismicRichText field={slice.primary.heading} fallback={<h2>The AI Slop Museum</h2>} />
      </div>
      <p className="slop-disclaimer">
        All works generated by a computer that has never tasted beer. Captions verified by the same computer.
      </p>
      <div className="slop-grid">
        {slice.primary.items.map((item, i) => (
          <figure key={i} className="slop-item" style={{ "--rot": `${wobble(i + 31, 7)}deg` }}>
            <PrismicNextImage field={item.image} className="shaky-img" fallbackAlt="" />
            <figcaption>
              <span>{item.caption}</span>
              {item.confidence !== null ? (
                <span className="confidence">AI confidence: {item.confidence}%</span>
              ) : null}
            </figcaption>
          </figure>
        ))}
      </div>
    </section>
  );
}
